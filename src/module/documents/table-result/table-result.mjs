import { icons } from "../../constants/display/icons.mjs";
import * as dataMixins from "../../data/mixins/_module.mjs";
import { ConstructionNode, Panel } from "../../data/pseudo-documents/_module.mjs";
import { mixClasses } from "../../helpers/construction.mjs";
import { makeIcon } from "../../helpers/icon.mjs";
import * as documentMixins from "../mixins/_module.mjs";

const { TableResult } = foundry.documents;

/**
 * The Teriock TableResult implementation.
 * @mixes BaseDocument
 * @mixes PanelData
 * @mixes EmbeddableData
 */
export default class TeriockTableResult
  extends mixClasses(
    TableResult,
    documentMixins.BaseDocumentMixin,
    dataMixins.PanelDataMixin,
    dataMixins.EmbeddableDataMixin,
  )
{
  /**
   * Typed identifier for the referenced document on document-type results.
   * @returns {TypedIdentifier|null}
   */
  get documentIdentifier() {
    if (this.type !== "document") { return null; }
    return this.getFlag("teriock", "documentIdentifier") || null;
  }

  /** @inheritDoc */
  get embedParts() {
    return Object.assign(super.embedParts, { makeTooltip: true, subtitle: this.type, text: this.parent.name || "" });
  }

  /**
   * Activations generated by this table result.
   * @returns {Promise<Activation[]>}
   */
  async getActivations() {
    const acts = teriock.data.pseudoDocuments.activations;
    if (!this.documentUuid) { return []; }
    const parsed = foundry.utils.parseUuid(this.documentUuid);
    if (!parsed) { return []; }
    const doc = await fromUuid(this.documentUuid);
    if (!doc) { return []; }
    const activations = [];
    const name = doc.fullName ?? doc.name ?? "";
    if (doc.documentName === "Actor") {
      const label = _loc("TERIOCK.AUTOMATIONS.Summon.BUTTONS.placeNamed", {
        name: doc?.name || _loc("TERIOCK.AUTOMATIONS.Summon.BUTTONS.defaultName"),
      });
      activations.push(new acts.SummonActivation({ display: { label }, uuids: [this.documentUuid] }));
    }
    if (doc.documentName === "Macro") {
      activations.push(new acts.MacroActivation({ display: { label: name }, primaryMacro: this.documentUuid }));
    }
    if (["ActiveEffect", "Item", "RollTable"].includes(doc.documentName)) {
      const label = _loc("TERIOCK.COMMANDS.UseDocument.useNamed", { name });
      const icon = TERIOCK.config.document[doc.type]?.icon;
      activations.push(
        new acts.UseExternalActivation({ display: { icon, label }, options: { icon, label, uuid: this.documentUuid } }),
      );
    }
    if (["ActiveEffect", "Item"].includes(doc.documentName) && doc.type !== "ability") {
      const label = name
        ? _loc("TERIOCK.AUTOMATIONS.AddDocuments.BUTTONS.inferred", { name })
        : _loc("TERIOCK.AUTOMATIONS.AddDocuments.BUTTONS.default");
      activations.push(
        new acts.AddDocumentsActivation({
          constructionNodes: ConstructionNode.toCollectionObject([{ globalUuids: [this.documentUuid] }]),
          display: { label },
          target: ["imbuement", "property"].includes(doc.type) ? "armament" : "actor",
        }),
      );
    }
    return activations;
  }

  /** @inheritDoc */
  getEmbedContextMenuEntries(doc) {
    return [{
      icon: makeIcon(TERIOCK.display.icons.ui.document, "contextMenu"),
      label: _loc("TERIOCK.SYSTEMS.TableResult.MENU.open"),
      onClick: async () => await (await fromUuid(this.documentUuid))?.sheet.render(true),
      visible: () => this.documentUuid,
    }, ...super.getEmbedContextMenuEntries(doc)];
  }

  /** @inheritDoc */
  async getPanelParts() {
    /** @type {Teriock.Panels.PanelParts} */
    const parts = await super.getPanelParts();
    parts.icon = icons.document.tableResult;
    parts.label = _loc("TERIOCK.SYSTEMS.TableResult.PANELS.tableResult");
    parts.img = this.icon;
    parts.blocks.push({ text: this.description, title: _loc("TERIOCK.SYSTEMS.Child.FIELDS.description.label") });
    parts.bars.push({
      icon: TERIOCK.display.icons.ui.info,
      label: _loc("TERIOCK.SYSTEMS.TableResult.PANELS.resultType"),
      wrappers: [this.type],
    });
    if (this.documentUuid) {
      const document = await fromUuid(this.documentUuid);
      if (document) {
        parts.associations = [Panel.toAssociation([document], "TERIOCK.SYSTEMS.TableResult.PANELS.documents")];
      }
    }
    return parts;
  }

  /** @inheritDoc */
  prepareBaseData() {
    super.prepareBaseData();
    if (this.documentIdentifier && !this.documentUuid) {
      this.documentUuid = game.teriock.identifiers.get(this.documentIdentifier);
    }
  }

  /** @inheritDoc */
  toObject(source) {
    const obj = super.toObject(source);
    // Forcibly include a UUID in object if possible so that embedded roll tables include them.
    if (obj?.type === "document" && obj?.flags?.teriock?.documentIdentifier && !obj?.documentUuid) {
      obj.documentUuid = this.documentUuid;
    }
    return obj;
  }
}
