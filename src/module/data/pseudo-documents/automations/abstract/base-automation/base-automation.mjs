import { mergeMetadata } from "../../../../../helpers/construction.mjs";
import MechanicPseudoDocument from "../../../abstract/mechanic-pseudo-document/mechanic-pseudo-document.mjs";

const { fields } = foundry.data;

/** Legacy trigger keys that are now expressed as {@link BaseAutomation#interactInExecution}. */
const EXECUTION_TRIGGERS = new Set(["execute", "executeInput", "preExecute"]);

export default class BaseAutomation extends MechanicPseudoDocument {
  /** @inheritDoc */
  static LOCALIZATION_PREFIXES = [...super.LOCALIZATION_PREFIXES, "TERIOCK.AUTOMATIONS.Base"];

  /**
   * @inheritDoc
   * @type {Teriock.Metadata.AutomationMetadata}
   */
  static metadata = mergeMetadata(super.metadata, {
    documentName: "Automation",
    tags: { changes: false, interactInExecution: false, useInExecution: false },
    typed: true,
  });

  /** @inheritDoc */
  static get TYPE_MODELS() {
    return this.getTypeModels(teriock.data.pseudoDocuments.automations);
  }

  /** @inheritDoc */
  static defineSchema() {
    const schema = Object.assign(super.defineSchema(), {
      display: new fields.SchemaField({ label: new fields.StringField({ placeholder: _loc("COMMON.Default") }) }),
    });
    if (this.metadata.tags.interactInExecution) { schema.interactInExecution = new fields.BooleanField(); }
    if (this.metadata.tags.useInExecution) { schema.useInExecution = new fields.BooleanField({ initial: true }); }
    return schema;
  }

  /** @inheritDoc */
  static migrateData(source, options) {
    if ("selectInExecution" in source) {
      source.interactInExecution ||= source.selectInExecution;
      delete source.selectInExecution;
    }
    if (EXECUTION_TRIGGERS.has(source.trigger)) {
      source.interactInExecution = true;
      delete source.trigger;
    }
    return super.migrateData(source, options);
  }

  /**
   * Paths for displays data on the activations this makes.
   * @returns {string[]}
   */
  get _displayPaths() {
    return ["display.label"];
  }

  /**
   * Higher priority automations are applied to executions after lower priority ones.
   * @returns {number}
   */
  get _executionPriority() {
    return 0;
  }

  /**
   * Trigger and display paths.
   * @returns {string[]}
   */
  get _triggerDisplayPaths() {
    const paths = [...(this._triggerPaths ?? [])];
    if (this.makesOneActivation && !this.useInExecution) { paths.push(...this._displayPaths); }
    return paths;
  }

  /**
   * Whether a copy of this gets added to generated effects.
   * @returns {boolean}
   */
  get canAddToEffect() {
    return Object.keys(teriock.data.systems.effects.ConsequenceSystem.automationTypes).includes(this.type);
  }

  /** @inheritDoc */
  get canCrit() {
    return super.canCrit && (this.canModifyEffectData || !this.hasEffectDataToModify);
  }

  /**
   * Whether this leaves its activations on the chat message.
   * @returns {boolean}
   */
  get canGetActivations() {
    return !this.useInExecution;
  }

  /**
   * Whether this can modify effect data.
   * @returns {boolean}
   */
  get canModifyEffectData() {
    return this.canAddToEffect;
  }

  /**
   * Whether this can modify generated effect data.
   * @returns {boolean}
   */
  get hasEffectDataToModify() {
    return this.document?.type === "ability";
  }

  /**
   * Whether this makes at most one activation.
   * @returns {boolean}
   */
  get makesOneActivation() {
    return true;
  }

  /**
   * Apply this automation's display data to the activation it made.
   * @param {Activation[]} activations
   * @returns {Activation[]}
   */
  _applyDisplayToActivations(activations) {
    if (activations.length === 1 && this.display?.label) {
      activations[0].updateSource({ "display.label": this.display.label });
    }
    return activations;
  }

  /**
   * Activations that can be generated by this automation.
   * @param {Teriock.Automations.GetActivationsOptions} [_options]
   * @returns {Promise<Activation[]>}
   */
  async _getActivations(_options = { execution: null, rollData: {} }) {
    return [];
  }

  /**
   * Data for the copy of this that is attached to effects generated by an execution.
   * @param {BaseExecution} _execution
   * @returns {object}
   */
  _getEffectAutomationData(_execution) {
    return Object.assign(this.toObject(), { _id: foundry.utils.randomID() });
  }

  /**
   * Activations generated by this automation.
   * @param {Teriock.Automations.GetActivationsOptions} [options]
   * @returns {Promise<Activation[]>}
   */
  async getActivations(options = { execution: null, rollData: {} }) {
    return this.canGetActivations ? this._applyDisplayToActivations(await this._getActivations(options)) : [];
  }

  /**
   * Changes generated by this automation.
   * @returns {Teriock.Changes.QualifiedChangeData[]}
   */
  getChanges() {
    return [];
  }

  /** @inheritDoc */
  getCompetence(scope) {
    return scope?.execution?.competence?.raw ?? super.getCompetence(scope);
  }

  /**
   * User interaction and data preparation that happens once an execution is completed.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async interactOnExecutionCompletion(_execution) {}

  /**
   * User interaction and data preparation that happens as part generating effect data.
   * @param {BaseExecution} _execution
   * @returns {Promise<void>}
   */
  async interactOnExecutionEffectData(_execution) {}

  /**
   * User interaction and data preparation that happens as part of an execution getting input.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async interactOnExecutionInput(_execution) {}

  /**
   * Modify an ongoing execution. This happens after user inputs are complete.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async modifyExecution(_execution) {}

  /**
   * Modify an execution as it is being constructed.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async modifyExecutionConstruction(_execution) {}

  /**
   * Modify the activation that adds effects generated by an execution.
   * @param {BaseExecution} _execution
   * @param {AddDocumentsActivation} _activation
   * @returns {Promise<void>}
   */
  async modifyExecutionEffectActivation(_execution, _activation) {}

  /**
   * Modify data of effects generated by an execution.
   * @param {BaseExecution} execution
   * @param {object} data
   * @returns {Promise<void>}
   */
  async modifyExecutionEffectData(execution, data) {
    if (!this.canAddToEffect) { return; }
    const automations = foundry.utils.getProperty(data, "system.automations") ?? {};
    const automationData = this._getEffectAutomationData(execution);
    automations[automationData._id] = automationData;
    foundry.utils.setProperty(data, "system.automations", automations);
  }

  /**
   * Modify the construction nodes attached to effects generated by an execution.
   * @param {BaseExecution} _execution
   * @param {object[]} _nodes
   * @returns {Promise<void>}
   */
  async modifyExecutionEffectNodes(_execution, _nodes) {}

  /** @inheritDoc */
  prepareData() {
    super.prepareData();
    if (this.metadata.tags.interactInExecution && this.triggers?.size) { this.interactInExecution = false; }
    if (this.metadata.tags.useInExecution && !this.interactInExecution) { this.useInExecution = false; }
  }
}
