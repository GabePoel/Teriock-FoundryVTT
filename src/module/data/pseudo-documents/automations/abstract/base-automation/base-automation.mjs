import MechanicPseudoDocument from "../../../abstract/mechanic-pseudo-document/mechanic-pseudo-document.mjs";

export default class BaseAutomation extends MechanicPseudoDocument {
  /** @inheritDoc */
  static LOCALIZATION_PREFIXES = [...super.LOCALIZATION_PREFIXES, "TERIOCK.AUTOMATIONS.Base"];

  /** @inheritDoc */
  static get metadata() {
    return Object.assign(super.metadata, {
      changes: false,
      crit: false,
      documentName: "Automation",
      label: _loc("DOCUMENT.Automation"),
      macro: false,
      trigger: false,
      typed: true,
    });
  }

  /**
   * Higher priority automations are applied to executions after lower priority ones.
   * @returns {number}
   */
  get _executionPriority() {
    return 0;
  }

  /**
   * Whether this is passive or not.
   * @returns {boolean}
   */
  get isPassive() {
    if (this.document.type === "ability") { return this.document?.system?.maneuver === "passive"; }
    return this.document.type === "property";
  }

  /**
   * Data for the copy of this that is attached to effects generated by an execution.
   * @param {BaseExecution} _execution
   * @returns {object}
   */
  _getEffectAutomationData(_execution) {
    return Object.assign(this.toObject(), { _id: foundry.utils.randomID() });
  }

  /**
   * Activations generated by this automation.
   * @param {Teriock.Automations.GetActivationsOptions} [_options]
   * @returns {Promise<Activation[]>}
   */
  async getActivations(_options = { execution: null, rollData: {} }) {
    return [];
  }

  /**
   * Changes generated by this automation.
   * @returns {Teriock.Changes.QualifiedChangeData[]}
   */
  getChanges() {
    return [];
  }

  /** @inheritDoc */
  getCompetence(scope) {
    return scope?.execution?.competence?.raw ?? super.getCompetence(scope);
  }

  /**
   * User interaction and data preparation that happens once an execution is completed.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async interactOnExecutionCompletion(_execution) {}

  /**
   * User interaction and data preparation that happens as part generating effect data.
   * @param {BaseExecution} _execution
   * @returns {Promise<void>}
   */
  async interactOnExecutionEffectData(_execution) {}

  /**
   * User interaction and data preparation that happens as part of an execution getting input.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async interactOnExecutionInput(_execution) {}

  /**
   * Modify an ongoing execution. This happens after user inputs are complete.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async modifyExecution(_execution) {}

  /**
   * Modify an execution as it is being constructed.
   * @param {BaseExecution} _execution
   * @returns {Promise<false|void>}
   */
  async modifyExecutionConstruction(_execution) {}

  /**
   * Modify the activation that adds effects generated by an execution.
   * @param {BaseExecution} _execution
   * @param {AddDocumentsActivation} _activation
   * @returns {Promise<void>}
   */
  async modifyExecutionEffectActivation(_execution, _activation) {}

  /**
   * Modify data of effects generated by an execution.
   * @param {BaseExecution} execution
   * @param {object} data
   * @returns {Promise<void>}
   */
  async modifyExecutionEffectData(execution, data) {
    if (!(this.type in CONFIG.ActiveEffect.dataModels.consequence.automationTypes)) { return; }
    const automations = foundry.utils.getProperty(data, "system.automations") ?? {};
    const automationData = this._getEffectAutomationData(execution);
    automations[automationData._id] = automationData;
    foundry.utils.setProperty(data, "system.automations", automations);
  }

  /**
   * Modify the construction nodes attached to effects generated by an execution.
   * @param {BaseExecution} _execution
   * @param {object[]} _nodes
   * @returns {Promise<void>}
   */
  async modifyExecutionEffectNodes(_execution, _nodes) {}
}
